import mongoose from 'mongoose';

const LinkSchema = new mongoose.Schema({
  title: { type: String },
  url: { type: String },
  icon: { type: String },
  type: { type: String },
}, { _id: false });

const ProfileSchema = new mongoose.Schema({
  user: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true, unique: true },
  userType: { type: String, enum: ['ind', 'org'], default: 'ind' },
  fullName: { type: String },
  gender: { type: String },
  jobTitle: { type: String },
  companyName: { type: String },
  company: { type: String },
  jobCategory: { type: String },
  phoneNumber: { type: String },
  whatsappNumber: { type: String },
  companyAddress: { type: String },
  companyAddressType: { type: String, enum: ['address', 'link'] },
  dob: { type: String },
  bio: { type: String },
  location: { type: String },
  website: { type: String },
  industry: { type: String },
  companySize: { type: String },
  username: { type: String },
  cardThemeColor: { type: String },
  buttonThemeColor: { type: String },
  links: [LinkSchema],
  avatarUrl: { type: String },
  userProfilePhotoPath: { type: String },
  logoImagePath: { type: String },
  companyRepresentativePhotoPath: { type: String },
  selectedPlanName: { type: String },
  isYearly: { type: Boolean },
  offeringType: { type: String },
  offeringDescription: { type: String },
  offeringImagePaths: [String],
  offeringCaptions: [String],
  websiteLink: { type: String },
  instagramLink: { type: String },
  linkedinLink: { type: String },
  twitterLink: { type: String },
  keepMeSignedIn: { type: Boolean, default: false },
  isBusiness: { type: Boolean, default: false },
}, { timestamps: true });

export default mongoose.model('Profile', ProfileSchema);
